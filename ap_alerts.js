/* ap_alerts.js — 請求書の AI のコメント（AIComment の1行ずつ）を、確認の画面でどう出すかに見分ける（経費・仕入で共通）
   決め方：2026-11-25 の「読み取りと気づき 棚卸し」で依頼者が選んだ表（話題ごとに 要修正／要確認／参考／出さない）
   使い方：APAlerts.kind(文, { area: '経費' | '仕入', ai: AI の状態, linked: 仕入先に付いたか, bankSame: 選んだ振込先が振込先マスタと同じか }) → 'fix' | 'act' | 'info' | 'hide'
     fix＝要修正（直すまで進めない） act＝要確認（上に出す。✔ 確かめた で片付ける） info＝参考（AI のメモにしまう） hide＝出さない（済んでいる・アプリが調べる）
   新しい指示の答えは、文の頭に印がある（【要確認・話題】【参考・話題】【要修正・話題】）。印があれば印のとおり、無い今までの文は言葉で見分ける */
(function () {
  'use strict';
  const MARK = /^【(要修正|要確認|参考)(?:[・:：]([^】]*))?】\s*/;
  // 文の頭の印を外す（画面に出すとき）。{ level, topic, text }
  function tag(s) { const t = String(s || ''), m = t.match(MARK); return m ? { level: m[1], topic: m[2] || '', text: t.replace(MARK, '') } : { level: '', topic: '', text: t }; }
  const ASK = /(確か|確認して|確認が必要|確認ください|要確認|原本で|見てください)/;
  function kind(s, ctx) {
    ctx = ctx || {};
    const area = ctx.area === '仕入' ? '仕入' : '経費', g = tag(s), t = g.text;
    // 振込先が複数で1つを選んだ：選んだ口座が振込先マスタと同じなら、確かめることは無いので参考（2026-11-26 依頼者と決めた）
    const pickedSame = ctx.bankSame && /複数|2つ|二つ|選んだ|採用/.test(t) && !/切れ|補い|補った|桁|判読|読めな|推測|違う|異な|債権譲渡|決済代行/.test(t);
    if (g.level) return g.level === '要確認' && pickedSame ? 'info' : g.level === '要修正' ? 'fix' : g.level === '要確認' ? 'act' : 'info';
    // ── アプリが書き足す文（読み取りのとき）
    if (/^AI の読み取りに失敗しました|読み取りが.{0,10}終わりません/.test(t)) return ctx.ai === 'AI確認済' ? 'hide' : 'fix';   // 読み直して読めたあとの古い失敗の文は出さない
    if (/請求書が.{0,3}通以上|通以上あります|分けて渡し直/.test(t)) return 'fix';
    if (/^受付の金額/.test(t)) return 'act';
    if (/^引落日 /.test(t)) return 'info';
    if (/税込÷1\.1 ?で出しました/.test(t)) return 'info';
    if (/^仕訳は、読んだ明細から/.test(t)) return 'info';
    if (/^仕訳を明細から作り直(そうとしましたが|せませんでした)/.test(t)) return 'act';
    if (/経費に回しました/.test(t)) return 'info';
    if (/^向きを直して保存/.test(t)) return 'hide';
    if (/向きが違うページがありますが/.test(t)) return 'act';
    if (/^仕入先：.*に付けました|^AI の候補/.test(t)) return 'hide';
    if (/税抜の合計の印字/.test(t)) return 'act';
    // ── AI が書く文（話題ごと）。上から順に当てる
    if (/撮り直し|添付されていない|ページが(足りな|抜け)|(明細|添付|別紙).{0,15}(ページ目のみ|入っていない|添付されていない|見当たらない|足りない)/.test(t)) return 'act';                 // 写り：撮り直しが要るもの
    if (/手書き.{0,10}(訂正|修正)|訂正線|二重線|訂正版|訂正があります|訂正あり|\((正|誤)\)|「\((正|誤)\)」/.test(t)) return 'act';   // 手書きの訂正・訂正版
    if (/二重/.test(t)) return 'act';
    if (/請求書ではな|案内状|受け取り側|受け取る側|受取側|協賛金を受け取|出欠/.test(t)) return 'act';               // 支払の中身の注意
    if (/資産|前払|前金|ファイナンス/.test(t)) return 'act';
    if (/リース/.test(t)) return /(新規|初回|最終回|再リース|車種|確か|確認)/.test(t) ? 'act' : 'info';   // リースの説明だけは参考
    if (/でんさいの可能性|支払方法がでんさい|決済代行|入金が確認できません|先方負担/.test(t)) return 'act';
    if (/適格請求書(発行事業者)?でな|登録番号(の)?ない.{0,10}(分|事業者)|仕入税額控除/.test(t)) return 'act';
    if (/(振込先|口座).{0,20}(マスタ|登録).{0,10}(違|異な)|違う口座|口座が変わ/.test(t)) return 'act';
    // 支払方法・口座振替・引落：支払方法を決めた説明と、引落口座・振替日の説明は出さない（支払回はアプリの決まりで決める）。払う月と合わないときだけ要確認
    if (/支払方法/.test(t) && /(未定|とした|としました|と判断|とし[、。]|記載どおり)/.test(t) && !/(違う|合わ)/.test(t)) return 'hide';
    if (/口座振替|自動振替|引落|引き落|振替日|振替口座|振替予定|納入告知/.test(t)) return /(払う月|支払回|月払い).{0,30}(合うか|合わな|合わず|合いません|違|異な)|(合うか|合わな|違).{0,20}(払う月|支払回)/.test(t) && !/合っています|一致/.test(t) ? 'act' : 'hide';
    if (/(区分|拠点|宛名|宛先).{0,40}(工場|本社|経費|仕入|営業所|支店|個人)|(工場|本社).{0,30}(区分|拠点)|経費の請求書かも|工場あて|工場宛|当社宛|会社宛/.test(t)) return area === '仕入' && ctx.linked ? 'hide' : ASK.test(t) ? 'act' : 'info';
    // 振込先・口座（複数の口座から選んだ・名義が切れている・桁を補った）：経費だけ。仕入は振込先マスタの口座を使う
    if (/(銀行|支店)コード/.test(t) && /(記載|印字|書かれ).{0,8}(なし|ない|ありません|無)|空欄|全銀/.test(t)) return 'hide';
    if (/振込先|口座|名義|銀行/.test(t) && !/振込手数料|振込料/.test(t)) {
      if (area === '仕入') return 'hide';
      if (pickedSame) return 'info';
      if (/複数|選んだ|採用|切れ|補い|補った|桁|判読|読めな|推測|違|債権譲渡|決済代行/.test(t) && !/伏字|伏せ字|マスク/.test(t)) return 'act';
      return /(記載|印字).{0,10}(なし|ない|なく|ありません|無)|未記載|伏字|伏せ字|マスク|のみ/.test(t) ? 'hide' : 'info';
    }
    if (/振込手数料|振込料/.test(t)) return 'hide';                                   // いつもの当社負担（先方負担は上で要確認）
    if (/登録番号/.test(t)) return 'info';                                            // 読みにくいだけはアプリがマスタ・前の月と比べる
    if (/SMILE ?の額|支払残高|今回支払残高|今月の支払先リスト|仕入先リスト|支払先リスト|PayeeCode|仕入先コード|同じ相手|同一の相手/.test(t)) return 'hide';
    if (/預り金|源泉|住民税|納付/.test(t)) return 'info';
    // 支払期日・支払回・払う月：記載なし・未定・仮置きは出さない。払う月と合わないときだけ要確認
    if (/支払期日|期日|支払回|払う月|お支払日|お支払予定|支払予定日|振替日|納期限|支払条件/.test(t)) return /(合わな|合わず|合いません|違|ずれ)/.test(t) && /(払う月|支払回|期日)/.test(t) && !/合います|合わせ/.test(t) ? 'act' : 'hide';
    if (/請求(書)?(No|NO|Ｎｏ|番号)|伝票No|請求日|発行日|吉日/.test(t) && /(なし|ない|ありません|無|空|仮)/.test(t)) return 'hide';
    if (/初めての支払先|取引のない支払先|過去に.{0,6}(無|な)い支払先/.test(t)) return 'hide';
    if (/科目|部門|勘定|仕訳|交際費|会議費|雑費|福利厚生|広告宣伝|消耗品|諸会費|販売促進/.test(t)) return /迷|判断でき|分かりません|わかりません/.test(t) ? 'act' : 'info';   // 理由は仕訳の行に
    if (/税率(は)?不明|課税か確かめ|税込総額か/.test(t)) return 'act';
    if (/税抜|税込|消費税|内税|外税|御買上|今回請求額|合計|小計|端数|一致/.test(t)) return /(合わ(ない|ず|ません)|一致しな|一致せ|違い|差が|異な)/.test(t) ? 'act' : 'hide';
    if (/明細|品名|行目|数量|単価|伝票|納品|受入|返品|値引/.test(t)) return 'info';
    if (/読みにく|読み取りにく|判読|不鮮明|印影|写真のため|重なって/.test(t)) return 'info';
    // どれにも当たらない：頼んでいる（確かめて）ものは要確認、説明だけなら参考
    return ASK.test(t) ? 'act' : 'info';
  }
  window.APAlerts = { kind, tag };
})();
